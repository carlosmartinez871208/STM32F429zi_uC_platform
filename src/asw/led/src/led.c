void led_init ()
{
    dev_abs_set_gpio_clock (PORTG_CLOCK_EN,true);
    IoHwAb_port_reset_pin (PORTG,RESET_PIN_13);
    IoHwAb_port_pin_mode_output (PORTG,PG13_CONFIG_OUTPUT);
}

void led_on ()
{
    IoHwAb_set_pin_high (PORTG,LD3);
}

void led_off ()
{
    IoHwAb_set_pin_low (PORTG,LD3);
}

