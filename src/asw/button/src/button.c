extern void button_init ()
{
    dev_abs_set_gpio_clock (PORTA_CLOCK_EN,true);
    IoHwAb_port_pin_mode_input (PORTA,PA0_CONFIG_INPUT);
}

extern bool button_state ()
{
    return IoHwAb_get_pin_state(PORTA,B1_USER);
}

