void sbc_vtor_config_offset (uint32_t mem_base,uint32_t tab_offset)
{
    SBC_VTOR = (mem_base|tab_offset);
}

void sbc_icsr_config_systick_pending_bit (bool config_bit)
{
    if(true==config_bit)
    {
        SBC_ICSR |= SBC_ISCR_SET_PEN_BIT;
    }
    else
    {
        SBC_ICSR &= (~SBC_ISCR_SET_PEN_BIT);
    }
}

